import type { Report } from "./types";
import { CATEGORIES, SEVERITIES, SEVERITY_ORDER } from "./constants";
import { gradeFor } from "./scoring";
import { formatBytes, formatCount, formatDuration } from "./utils";

/**
 * Markdown export.
 *
 * Produces a self-contained document you can drop into a README, a PR
 * description, a ticket or a Slack message — the report's substance without the
 * UI. Deliberately plain Markdown so it renders anywhere.
 */

function esc(text: string): string {
  // Escape the few sequences that would break table cells or headings.
  return text.replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();
}

function rel(iso: string): string {
  const then = new Date(iso).getTime();
  if (!Number.isFinite(then)) return "unknown";
  const days = Math.floor((Date.now() - then) / 86_400_000);
  if (days <= 0) return "today";
  if (days === 1) return "yesterday";
  if (days < 30) return `${days} days ago`;
  const months = Math.floor(days / 30);
  if (months < 12) return `${months} month${months === 1 ? "" : "s"} ago`;
  return `${Math.floor(months / 12)} year(s) ago`;
}

export function reportToMarkdown(report: Report): string {
  const r = report;
  const grade = gradeFor(r.healthScore);
  const out: string[] = [];

  /* ---- Title ------------------------------------------------------ */
  out.push(`# ${r.repo.fullName} — Codebase Health Report`);
  out.push("");
  out.push(
    `> **Health score ${r.healthScore}/100** (Grade ${grade.letter} · ${grade.label}) · ` +
      `${formatCount(r.structure.fileCount)} files · ${formatCount(r.findings.length)} findings`
  );
  out.push("");
  if (r.repo.description) {
    out.push(r.repo.description);
    out.push("");
  }
  out.push(
    `Generated by [Haryn AI](https://github.com) on ${new Date(r.completedAt).toUTCString()} · ` +
      `analysis took ${formatDuration(r.durationMs)}.`
  );
  out.push("");

  /* ---- Repository ------------------------------------------------- */
  out.push("## Repository");
  out.push("");
  out.push("| | |");
  out.push("| --- | --- |");
  out.push(`| Repository | [${r.repo.fullName}](${r.repo.url}) |`);
  if (r.repo.license) out.push(`| License | ${r.repo.license} |`);
  if (!r.repo.metaPartial) {
    out.push(`| Stars | ${formatCount(r.repo.stars)} |`);
    out.push(`| Forks | ${formatCount(r.repo.forks)} |`);
  }
  out.push(`| Default branch | \`${r.repo.defaultBranch}\` |`);
  out.push(
    `| Size | ${formatCount(r.structure.fileCount)} files across ${formatCount(r.structure.dirCount)} directories (${r.structure.sizeClass}) |`
  );
  out.push(`| Analysed | ${formatCount(r.stats.sourceFilesSampled)} files, ${formatBytes(r.stats.bytesAnalyzed)} |`);
  if (r.repo.pushedAt) out.push(`| Last push | ${rel(r.repo.pushedAt)} |`);
  out.push("");
  if (r.languages.length) {
    out.push(
      `**Languages:** ${r.languages
        .slice(0, 6)
        .map((l) => `${l.name} ${l.percent.toFixed(0)}%`)
        .join(" · ")}`
    );
    out.push("");
  }

  /* ---- Summary ---------------------------------------------------- */
  out.push("## Summary");
  out.push("");
  out.push(r.summary);
  out.push("");

  /* ---- Activity --------------------------------------------------- */
  if (r.activity && (r.activity.totalCommits || r.activity.contributors.length)) {
    const a = r.activity;
    out.push("## Activity");
    out.push("");
    out.push(`- **Total commits:** ${formatCount(a.totalCommits)}`);
    out.push(`- **Contributors:** ${formatCount(a.contributors.length)}`);
    if (a.lastCommitAt) out.push(`- **Last commit:** ${rel(a.lastCommitAt)}`);
    out.push(
      `- **Momentum:** ${a.recentMonthly} commits in the last 4 weeks vs ${a.priorMonthly} in the previous 4`
    );
    out.push("");

    if (a.months?.length) {
      out.push("### Commit frequency");
      out.push("");
      out.push("| Month | Commits |");
      out.push("| --- | ---: |");
      a.months.forEach((m) => out.push(`| ${m.label} | ${m.total} |`));
      out.push("");
    }

    if (a.messageTypes?.length && a.messageStats) {
      out.push("### Commit messages");
      out.push("");
      out.push(
        `${a.messageStats.scanned} messages inspected (${a.messageStats.withBody} with a description), averaging ${a.messageStats.avgSubjectLength} characters.`
      );
      out.push("");
      out.push("| Type | Commits | Share |");
      out.push("| --- | ---: | ---: |");
      a.messageTypes.forEach((t) =>
        out.push(`| ${t.type} | ${t.count} | ${(t.share * 100).toFixed(0)}% |`)
      );
      out.push("");
    }

    if (a.authorStats?.length) {
      out.push("### Who committed");
      out.push("");
      out.push("| Author | Commits | Share | Last commit |");
      out.push("| --- | ---: | ---: | --- |");
      a.authorStats.slice(0, 15).forEach((x) =>
        out.push(
          `| ${esc(x.login)} | ${x.commits} | ${(x.share * 100).toFixed(0)}% | ${
            x.lastCommitAt ? rel(x.lastCommitAt) : "—"
          } |`
        )
      );
      out.push("");
    }

    if (a.recentCommits.length) {
      out.push("### Commit history");
      out.push("");
      out.push("| SHA | Type | Message | Author | When |");
      out.push("| --- | --- | --- | --- | --- |");
      a.recentCommits.slice(0, 60).forEach((c) => {
        out.push(
          `| \`${c.shortSha}\` | ${c.type} | ${esc(c.message)} | ${esc(c.author)} | ${
            c.date ? rel(c.date) : "—"
          } |`
        );
      });
      out.push("");
      if (a.recentCommits.length > 60) {
        out.push(
          `_Showing the 60 most recent of ${a.recentCommits.length} commits inspected._`
        );
        out.push("");
      }
    }
  }

  /* ---- Scores ----------------------------------------------------- */
  out.push("## Category scores");
  out.push("");
  out.push("| Category | Score | Weight | Issues |");
  out.push("| --- | ---: | ---: | ---: |");
  r.scores.forEach((s) => {
    out.push(
      `| ${s.label} | ${s.score}/100 | ${(s.weight * 100).toFixed(0)}% | ${s.issueCount} |`
    );
  });
  out.push("");

  /* ---- Severity breakdown ----------------------------------------- */
  const counts = SEVERITY_ORDER.map((sev) => ({
    sev,
    n: r.findings.filter((f) => f.severity === sev).length,
  })).filter((c) => c.n > 0);

  if (counts.length) {
    out.push("## Findings by severity");
    out.push("");
    out.push(counts.map((c) => `**${SEVERITIES[c.sev].label}:** ${c.n}`).join(" · "));
    out.push("");
  }

  /* ---- Prioritised actions ---------------------------------------- */
  if (r.recommendations.length) {
    out.push("## What to fix first");
    out.push("");
    r.recommendations.forEach((rec) => {
      out.push(
        `${rec.rank}. **[${rec.severity.toUpperCase()}]** ${esc(rec.title)}` +
          (rec.filePath ? ` — \`${rec.filePath}\`` : "") +
          ` _(${CATEGORIES[rec.category].label})_`
      );
    });
    out.push("");
  }

  /* ---- Findings --------------------------------------------------- */
  out.push("## Findings");
  out.push("");

  const byCategory = new Map<string, typeof r.findings>();
  for (const f of r.findings) {
    const list = byCategory.get(f.category);
    if (list) list.push(f);
    else byCategory.set(f.category, [f]);
  }

  for (const [cat, list] of byCategory) {
    const meta = CATEGORIES[cat as keyof typeof CATEGORIES];
    out.push(`### ${meta.label} (${list.length})`);
    out.push("");
    list
      .slice()
      .sort(
        (a, b) =>
          SEVERITIES[a.severity].order - SEVERITIES[b.severity].order ||
          b.confidence - a.confidence
      )
      .forEach((f) => {
        const loc = f.filePath
          ? ` — \`${f.filePath}${f.lineStart ? `:${f.lineStart}` : ""}\``
          : "";
        out.push(`- **[${f.severity.toUpperCase()}] ${esc(f.title)}**${loc}`);
        out.push(`  ${esc(f.description)}`);
        if (f.evidence) out.push(`  \`\`\`\n  ${f.evidence.split("\n").join("\n  ")}\n  \`\`\``);
        if (f.impact) out.push(`  _Impact:_ ${esc(f.impact)}`);
        out.push(`  _Fix:_ ${esc(f.recommendation)}`);
        if (f.isPotential) out.push(`  _Heuristic signal (confidence ${f.confidence.toFixed(2)}) — verify before acting._`);
        out.push("");
      });
  }

  /* ---- Architecture ----------------------------------------------- */
  if (r.architecture.nodes.length) {
    out.push("## Architecture");
    out.push("");
    out.push(r.architecture.summary);
    out.push("");
    out.push("| Layer | Type | Files |");
    out.push("| --- | --- | ---: |");
    r.architecture.nodes.forEach((n) => {
      out.push(`| ${esc(n.label)} | \`${n.type}\` | ${n.files} |`);
    });
    out.push("");
  }

  /* ---- Dependencies ----------------------------------------------- */
  out.push("## Dependencies");
  out.push("");
  const d = r.dependencies.stat;
  out.push(
    `${d.total} declared — ${d.healthy} healthy, ${d.outdated} outdated, ${d.vulnerable} vulnerable, ${d.unused} unused.`
  );
  out.push("");
  const vuln = r.dependencies.items.filter((i) => i.status === "vulnerable");
  if (vuln.length) {
    out.push("**Vulnerable packages**");
    out.push("");
    out.push("| Package | Version | Advisories |");
    out.push("| --- | --- | --- |");
    vuln.slice(0, 25).forEach((i) => {
      out.push(
        `| ${esc(i.name)} | \`${esc(i.version)}\` | ${(i.vulns ?? []).map((v) => v.id).join(", ") || "—"} |`
      );
    });
    out.push("");
  }

  /* ---- Testing ---------------------------------------------------- */
  out.push("## Testing");
  out.push("");
  out.push(
    `${r.testing.testFiles} test file(s) for ${r.testing.sourceFiles} source files (${(r.testing.ratio * 100).toFixed(1)}%).`
  );
  if (r.testing.frameworks.length) {
    out.push("");
    out.push(`Frameworks: ${r.testing.frameworks.join(", ")}.`);
  }
  if (r.testing.criticalUncovered.length) {
    out.push("");
    out.push(`Business-critical areas without tests: ${r.testing.criticalUncovered.join(", ")}.`);
  }
  out.push("");
  out.push(
    "_Coverage is estimated from test-file presence, not a measured coverage report._"
  );
  out.push("");

  /* ---- Footer ----------------------------------------------------- */
  out.push("---");
  out.push("");
  out.push(
    "Findings are advisory. Heuristic signals are labelled **potential** and carry a confidence value — treat this report as a starting point, not a security audit."
  );
  out.push("");
  out.push(`_Report id: \`${r.id}\`_`);
  out.push("");

  return out.join("\n");
}
