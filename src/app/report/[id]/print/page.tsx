import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { getReport } from "@/lib/store";
import {
  formatBytes,
  formatDate,
  formatDuration,
  gradeOf,
  rankedFindings,
  severityCounts,
  summaryExcerpt,
  systemicFixes,
  testEvidenceOf,
  topFindings,
  verificationOf,
  verdictOf,
} from "@/lib/pdf";
import type { Report } from "@/lib/types";
import { PrintTrigger } from "./PrintTrigger";
import "./print.css";

export const dynamic = "force-dynamic";

type PageParams = {
  params: Promise<{ id: string }>;
  searchParams: Promise<{ auto?: string }>;
};

export async function generateMetadata({ params }: PageParams): Promise<Metadata> {
  const { id } = await params;
  const report = await getReport(id);
  return {
    title: report
      ? `${report.repo.fullName} — Health Report (PDF) | Haryn AI`
      : "Report not found — Haryn AI",
  };
}

/* ------------------------------------------------------------------ */
/* Small presentational pieces                                         */
/* ------------------------------------------------------------------ */

function Header({ section, note }: { section: string; note: string }) {
  return (
    <div className="ph">
      <div className="brand">
        <div className="mark">H</div>
        <div>
          <div className="brand-name">Haryn AI</div>
          <div className="brand-sub">Engineering health report</div>
        </div>
      </div>
      <div className="ph-right">
        <div className="section-no">{section}</div>
        <div className="section-title">{note}</div>
      </div>
    </div>
  );
}

function Footer({ repo, page }: { repo: string; page: string }) {
  return (
    <div className="foot">
      <span>
        <b>{repo}</b> · generated by static analysis — no model, no execution
      </span>
      <span className="pageno">{page}</span>
    </div>
  );
}

function SeverityChip({ severity }: { severity: string }) {
  return <span className={`chip ${severity}`}>{severity}</span>;
}

/* ------------------------------------------------------------------ */
/* Page 1 — executive summary                                          */
/* ------------------------------------------------------------------ */

function PageOne({ report }: { report: Report }) {
  const counts = severityCounts(report.findings);
  const top = topFindings(report, 5);
  const [owner, name] = report.repo.fullName.split("/");
  const languages = report.languages.slice(0, 5);
  const stats = report.stats;

  return (
    <section className="page">
      <Header section="Section 01" note="Executive summary" />

      <h1 className="repo-name">
        <span className="owner">{owner}/</span>
        {name}
      </h1>

      <div className="meta">
        <span>
          Branch <b>{report.repo.defaultBranch}</b>
        </span>
        <span>
          Scanned <b>{formatDate(report.completedAt)}</b>
        </span>
        <span>
          Duration <b>{formatDuration(report.durationMs)}</b>
        </span>
        {report.activity?.totalCommits ? (
          <span>
            Commits <b>{report.activity.totalCommits.toLocaleString("en-GB")}</b>
          </span>
        ) : null}
        {report.repo.license ? (
          <span>
            Licence <b>{report.repo.license}</b>
          </span>
        ) : null}
      </div>

      <div className="hero">
        <div className="score-card">
          <div className="label">Overall health</div>
          <div className="score-row">
            <span className="score-value">{report.healthScore}</span>
            <span className="score-max">/ 100</span>
            <span className="grade">Grade {gradeOf(report.healthScore)}</span>
          </div>
          <div className="score-note">
            Weighted across eight categories: security, bugs, quality, testing,
            architecture, performance, dependencies and documentation.
          </div>
        </div>

        <div className="kpis">
          <div className={`kpi critical${counts.critical === 0 ? " zero" : ""}`}>
            <div className="kpi-n">{counts.critical}</div>
            <div className="kpi-l">Critical</div>
          </div>
          <div className={`kpi high${counts.high === 0 ? " zero" : ""}`}>
            <div className="kpi-n">{counts.high}</div>
            <div className="kpi-l">High</div>
          </div>
          <div className={`kpi medium${counts.medium === 0 ? " zero" : ""}`}>
            <div className="kpi-n">{counts.medium}</div>
            <div className="kpi-l">Medium</div>
          </div>
          <div className={`kpi low${counts.low === 0 ? " zero" : ""}`}>
            <div className="kpi-n">{counts.low}</div>
            <div className="kpi-l">Low</div>
          </div>
        </div>
      </div>

      <div className="h">
        <h2>Most important findings</h2>
        <span className="h-note">
          {counts.total} actionable of {report.findings.length} total
        </span>
      </div>

      <div className="rows">
        {top.map((f) => (
          <div className="row" key={`${f.rank}-${f.title}-${f.filePath ?? ""}`}>
            <span className={`dot ${f.severity}`} />
            <div>
              <div className="row-t">{f.title}</div>
              <div className="row-m">
                {f.filePath ? `${f.filePath}${f.lineStart ? `:${f.lineStart}` : ""}` : "repository-wide"}
                {f.occurrences > 1
                  ? `  ·  ×${f.occurrences} in ${f.files} file${f.files === 1 ? "" : "s"}`
                  : ""}
                {f.heuristic ? "  ·  heuristic" : "  ·  confirmed"}
              </div>
            </div>
            <div className="row-r">{f.categoryLabel}</div>
          </div>
        ))}
        {top.length === 0 ? (
          <div className="row">
            <span className="dot low" />
            <div className="row-t">No actionable findings were detected.</div>
            <div className="row-r" />
          </div>
        ) : null}
      </div>

      <div className="cols" style={{ marginTop: "6mm" }}>
        <div>
          <div className="h" style={{ marginTop: 0 }}>
            <h2>Tech stack</h2>
          </div>
          <div className="rows" style={{ marginTop: "1.5mm" }}>
            {languages.map((l) => (
              <div className="stat" key={l.name}>
                <span>{l.name}</span>
                <b>{l.percent.toFixed(1)}%</b>
              </div>
            ))}
            {languages.length === 0 ? <div className="stat"><span>Unknown</span><b>—</b></div> : null}
          </div>
        </div>

        <div>
          <div className="h" style={{ marginTop: 0 }}>
            <h2>Scan coverage</h2>
          </div>
          <div className="rows" style={{ marginTop: "1.5mm" }}>
            <div className="stat">
              <span>Files analysed</span>
              <b>{report.structure.fileCount.toLocaleString("en-GB")}</b>
            </div>
            <div className="stat">
              <span>Directories</span>
              <b>{report.structure.dirCount.toLocaleString("en-GB")}</b>
            </div>
            <div className="stat">
              <span>Source size</span>
              <b>{formatBytes(report.structure.totalBytes)}</b>
            </div>
            <div className="stat">
              <span>Code chunks indexed</span>
              <b>{(stats.indexedChunks ?? 0).toLocaleString("en-GB")}</b>
            </div>
          </div>
        </div>
      </div>

      <div className="h">
        <h2>Recommendation</h2>
      </div>
      <div className="panel" style={{ marginTop: "3mm" }}>
        <div style={{ fontSize: "2.55mm", lineHeight: 1.55, color: "var(--ink-2)" }}>
          {summaryExcerpt(report, 2)}
        </div>
        <div
          style={{
            marginTop: "2.4mm",
            display: "flex",
            alignItems: "flex-start",
            gap: "2.6mm",
          }}
        >
          <span
            className={`chip ${counts.critical > 0 ? "critical" : counts.high > 0 ? "high" : counts.medium > 0 ? "medium" : "teal"}`}
            style={{ flexShrink: 0, marginTop: "0.3mm" }}
          >
            {counts.critical > 0
              ? "Block release"
              : counts.high > 0
                ? "Fix before release"
                : counts.medium > 0
                  ? "Schedule"
                  : "No blockers"}
          </span>
          <span style={{ fontSize: "2.45mm", lineHeight: 1.5, color: "var(--ink-3)" }}>
            {verdictOf(report, counts)}
          </span>
        </div>
      </div>

      <Footer repo={report.repo.fullName} page="01 / 03" />
    </section>
  );
}

/* ------------------------------------------------------------------ */
/* Page 2 — detailed findings                                          */
/* ------------------------------------------------------------------ */

function PageTwo({ report }: { report: Report }) {
  const findings = topFindings(report, 5);

  return (
    <section className="page">
      <Header section="Section 02" note="Detailed findings" />

      <div className="h" style={{ marginTop: "5mm" }}>
        <h2>What is wrong, where, and why it matters</h2>
        <span className="h-note">
          Top {findings.length} distinct problems · ×N = one rule, many files
        </span>
      </div>

      {findings.map((f) => (
        <div className={`finding ${f.severity}`} key={`${f.rank}-${f.title}`}>
          <div className="f-head">
            <span className="f-n">{String(f.rank).padStart(2, "0")}</span>
            <span className="f-title">{f.title}</span>
            <SeverityChip severity={f.severity} />
            {f.occurrences > 1 ? (
              <span className="chip neutral">×{f.occurrences}</span>
            ) : null}
            <span className="chip neutral">
              {f.heuristic ? `${Math.round(f.confidence * 100)}% heuristic` : "confirmed"}
            </span>
          </div>

          <div className="f-loc">
            {f.filePath ? `${f.filePath}${f.lineStart ? `:${f.lineStart}` : ""}` : "repository-wide"}
            {f.inTest ? "  ·  test file" : ""}
            {f.occurrences > 1
              ? `  ·  repeated in ${f.files} file${f.files === 1 ? "" : "s"}`
              : ""}
          </div>

          <div className="f-grid">
            <div className="f-block">
              <span className="k">What it is</span>
              {f.what}
            </div>
            <div className="f-block f-fix">
              <span className="k">Fix</span>
              {f.fix ?? "No specific repair recorded for this rule."}
            </div>
          </div>

          {f.why ? (
            <div className="f-block" style={{ marginTop: "1.8mm" }}>
              <span className="k" style={{ color: "var(--red)" }}>
                Impact
              </span>
              {f.why}
            </div>
          ) : null}

          {f.evidence ? <div className="f-ev">{f.evidence}</div> : null}
        </div>
      ))}

      {findings.length === 0 ? (
        <div className="panel" style={{ marginTop: "4mm" }}>
          No actionable findings were detected by the rules that ran. That is a clean
          result for those rules — it is not proof of correctness, and code no rule
          covers is not reported as clean.
        </div>
      ) : null}

      <Footer repo={report.repo.fullName} page="02 / 03" />
    </section>
  );
}

/* ------------------------------------------------------------------ */
/* Page 3 — fixes and action plan                                      */
/* ------------------------------------------------------------------ */

function PageThree({ report }: { report: Report }) {
  const counts = severityCounts(report.findings);
  const verification = verificationOf(report);
  const systemic = systemicFixes(report, 3);
  const tests = testEvidenceOf(report);
  const deps = report.dependencies.stat;
  const graph = report.graph;
  const ranked = rankedFindings(report.findings).filter((f) => f.severity !== "info");
  const highest = ranked[0];
  const blocking = ranked.filter(
    (f) => f.severity === "critical" || f.severity === "high"
  );
  const backlog = ranked.filter((f) => f.severity === "medium" || f.severity === "low");
  const repeatCount = systemic.reduce((sum, s) => sum + s.count, 0);

  const skipped = graph?.skippedFiles ?? 0;
  const truncated = graph?.truncated ?? false;

  return (
    <section className="page">
      <Header section="Section 03" note="Fixes & action plan" />

      <div className="h" style={{ marginTop: "5mm" }}>
        <h2>Verification status</h2>
        <span className="h-note">What this report can and cannot claim</span>
      </div>

      <div className="status-row">
        <div className="status blue">
          <div className="n">{verification.detected}</div>
          <div className="l">Detected</div>
        </div>
        <div className="status teal">
          <div className="n">{verification.confirmed}</div>
          <div className="l">Confirmed in source</div>
        </div>
        <div className="status amber">
          <div className="n">{verification.heuristic}</div>
          <div className="l">Heuristic — verify</div>
        </div>
        <div className="status muted">
          <div className="n">{verification.fixesVerified}</div>
          <div className="l">Fixes verified</div>
        </div>
      </div>

      <div className="panel" style={{ marginTop: "3mm" }}>
        <div style={{ fontSize: "2.4mm", lineHeight: 1.55, color: "var(--ink-2)" }}>
          Every finding above was <b style={{ color: "var(--blue-2)" }}>detected</b> by a
          static rule reading the source. The repairs are{" "}
          <b style={{ color: "var(--amber)" }}>suggestions</b> — this analysis reads code,
          it never changes it, so <b>0 fixes are applied and 0 are verified</b>. A finding
          marked <i>heuristic</i> is a pattern to check, not a proven defect.
        </div>
      </div>

      <div className="cols" style={{ marginTop: "5mm" }}>
        <div>
          <div className="h" style={{ marginTop: 0 }}>
            <h2>Proposed fixes</h2>
            <span className="h-note">one decision each</span>
          </div>
          <div className="plan">
            {systemic.map((s, i) => (
              <div className="plan-item" key={s.rule}>
                <div className="plan-n">{String(i + 1).padStart(2, "0")}</div>
                <div>
                  <div className="plan-t">
                    {s.title} — {s.count}× across {s.files} file{s.files === 1 ? "" : "s"}
                  </div>
                  <div className="plan-d">{s.fix ?? "No specific repair recorded."}</div>
                </div>
              </div>
            ))}
            {systemic.length === 0 && highest ? (
              <div className="plan-item">
                <div className="plan-n">01</div>
                <div>
                  <div className="plan-t">{highest.title}</div>
                  <div className="plan-d">{highest.recommendation}</div>
                </div>
              </div>
            ) : null}
          </div>

          <div className="h">
            <h2>Tests</h2>
            <span className="h-note">evidence, not results</span>
          </div>
          <div className="panel" style={{ marginTop: "2.5mm" }}>
            <div className="stat" style={{ paddingTop: 0 }}>
              <span>Test suite executed</span>
              <b style={{ color: "var(--amber)" }}>No — not run</b>
            </div>
            <div className="stat">
              <span>Test files / source files</span>
              <b>
                {tests.testFiles} / {tests.sourceFiles}
              </b>
            </div>
            <div className="stat">
              <span>Frameworks detected</span>
              <b>{tests.frameworks.join(", ") || "none"}</b>
            </div>
            {tests.uncovered.length ? (
              <div className="stat">
                <span>Untested critical areas</span>
                <b style={{ color: "var(--amber)" }}>{tests.uncovered.join(", ")}</b>
              </div>
            ) : null}
          </div>
        </div>

        <div>
          <div className="h" style={{ marginTop: 0 }}>
            <h2>Dependencies</h2>
          </div>
          <div className="panel" style={{ marginTop: "2.5mm" }}>
            <div className="stat" style={{ paddingTop: 0 }}>
              <span>Declared</span>
              <b>{deps.total}</b>
            </div>
            <div className="stat">
              <span>Vulnerable</span>
              <b style={{ color: deps.vulnerable > 0 ? "var(--red)" : "var(--teal)" }}>
                {deps.vulnerable}
              </b>
            </div>
            <div className="stat">
              <span>Outdated</span>
              <b style={{ color: deps.outdated > 0 ? "var(--amber)" : "var(--teal)" }}>
                {deps.outdated}
              </b>
            </div>
            <div className="stat">
              <span>Healthy</span>
              <b>{deps.healthy}</b>
            </div>
          </div>

          <div className="h">
            <h2>Knowledge graph</h2>
          </div>
          <div className="panel" style={{ marginTop: "2.5mm" }}>
            <div className="stat" style={{ paddingTop: 0 }}>
              <span>Nodes / edges</span>
              <b>
                {(graph?.nodeCount ?? 0).toLocaleString("en-GB")} /{" "}
                {(graph?.edgeCount ?? 0).toLocaleString("en-GB")}
              </b>
            </div>
            <div className="stat">
              <span>Files parsed into the graph</span>
              <b>{graph?.parsedFiles ?? 0}</b>
            </div>
            <div className="stat">
              <span>Skipped as unsupported</span>
              <b style={{ color: skipped > 0 ? "var(--amber)" : "var(--teal)" }}>{skipped}</b>
            </div>
            <div className="stat">
              <span>Graph completeness</span>
              <b style={{ color: truncated ? "var(--amber)" : "var(--teal)" }}>
                {truncated ? "subset (cap reached)" : "complete"}
              </b>
            </div>
          </div>
        </div>
      </div>

      <div className="h">
        <h2>Next steps</h2>
        <span className="h-note">in this order</span>
      </div>
      <div className="plan">
        {blocking.length > 0 ? (
          <div className="plan-item">
            <div className="plan-n">01</div>
            <div>
              <div className="plan-t">
                Resolve the {blocking.length} critical and high findings first
              </div>
              <div className="plan-d">
                Start with {highest?.title.toLowerCase()} in {highest?.filePath ?? "the codebase"}.
                These are the ones worth delaying a release for.
              </div>
            </div>
          </div>
        ) : null}

        {systemic.length > 0 ? (
          <div className="plan-item">
            <div className="plan-n">{blocking.length > 0 ? "02" : "01"}</div>
            <div>
              <div className="plan-t">
                Collapse the repeated patterns — {systemic.length} rules, {repeatCount} findings
              </div>
              <div className="plan-d">
                One decision per rule removes {repeatCount} findings. This is the cheapest
                work in the report per edit.
              </div>
            </div>
          </div>
        ) : null}

        {backlog.length > 0 ? (
          <div className="plan-item">
            <div className="plan-n">{blocking.length > 0 ? (systemic.length > 0 ? "03" : "02") : "02"}</div>
            <div>
              <div className="plan-t">
                Schedule the {backlog.length} medium and low findings
              </div>
              <div className="plan-d">
                None of these block a release. Group them by area rather than fixing them
                one at a time.
              </div>
            </div>
          </div>
        ) : null}

        <div className="plan-item">
          <div className="plan-n">
            {String(1 + (blocking.length ? 1 : 0) + (systemic.length ? 1 : 0) + (backlog.length ? 1 : 0)).padStart(2, "0")}
          </div>
          <div>
            <div className="plan-t">Re-run the analysis to confirm the fixes</div>
            <div className="plan-d">
              This report cannot verify a repair: it read the code, it did not change it.
              Re-analysing after the fix is what turns a suggestion into a verified result.
            </div>
          </div>
        </div>
      </div>

      <div className="h">
        <h2>Limitations</h2>
      </div>
      <div className="panel" style={{ marginTop: "2.5mm" }}>
        <ul className="bullets">
          <li className="warn">
            No test suite was executed. The counts above describe test <i>files</i>, not
            passing or failing tests.
          </li>
          <li className="warn">
            {verification.heuristic} finding{verification.heuristic === 1 ? " is" : "s are"}{" "}
            heuristic — the rule reports a pattern, not a proven runtime defect.
          </li>
          {skipped > 0 ? (
            <li className="warn">
              {skipped} file{skipped === 1 ? "" : "s"} could not be parsed into the
              knowledge graph (unsupported language or binary).
            </li>
          ) : null}
          {truncated ? (
            <li className="warn">
              The knowledge graph hit its node cap, so call relationships are a subset.
            </li>
          ) : null}
          <li>
            Static analysis reads code; it does not run it. Behaviour that depends on
            runtime state, configuration or data is out of scope.
          </li>
          <li className="ok">
            {report.structure.fileCount.toLocaleString("en-GB")} files and{" "}
            {report.stats.bytesAnalyzed
              ? formatBytes(report.stats.bytesAnalyzed)
              : formatBytes(report.structure.totalBytes)}{" "}
            of source were parsed for this report.
          </li>
        </ul>
      </div>

      <Footer repo={report.repo.fullName} page="03 / 03" />
    </section>
  );
}

/* ------------------------------------------------------------------ */

export default async function PrintReportPage({ params, searchParams }: PageParams) {
  const { id } = await params;
  const { auto } = await searchParams;
  const report = await getReport(id);
  if (!report) notFound();

  return (
    <div className="pdf">
      <PageOne report={report} />
      <PageTwo report={report} />
      <PageThree report={report} />
      {auto ? <PrintTrigger /> : null}
    </div>
  );
}
